#ifndef VMC_MERGED_H
#define VMC_MERGED_H

/*
 * ============================================================================
 * VMC -- 单腿二维虚拟模型控制映射模块（对外唯一头文件）
 * ============================================================================
 *
 * 模块职责
 * --------
 * 把腿端的一对虚拟广义力（腿长方向推力 F、腿轴俯仰力矩 Tp）通过 Jacobian
 * 转置映射成两个驱动关节的力矩。
 *
 * 依赖约定
 * --------
 * 纯计算，无硬件依赖：不含电机、编码器、CAN、IMU、FreeRTOS、主控相关代码，
 * 也不关心左右腿、安装方向、传动比、电流环等上层概念。左右腿由上层分别调用
 * 本函数两次。本文件与 vmc_merged.c 成对使用，可独立拷贝到其他工程。
 *
 * 单位约定
 * --------
 * 力 N，力矩 N*m，Jacobian 各元素单位随其物理行含义而定（见下）。
 *
 * 接口分层
 * --------
 * 公开（对外，供上层调用）：
 *   - VMC_ConvertWrenchToJointTorque()   唯一的对外接口
 *
 * 本文件不导出任何内部实现（内部工具全部 static 于 vmc_merged.c）。
 *
 * 前置条件（重要）
 * ----------------
 * 调用方必须在进入本模块之前确认 Jacobian 可用，即 FiveBar 返回的
 * jacobian_valid == 1（或等价的非奇异判定）。VMC 只做有限值检查与矩阵转置
 * 乘法，**不做奇异检测**：传入奇异 Jacobian 会得到数值正常但物理无意义的
 * 关节力矩。
 *
 * 线程/重入性
 * -----------
 * 只读写调用方传入的对象，无可变全局状态，天然可重入；入参为 const，
 * 可并发只读共享同一 Jacobian。
 */

#include <stdint.h>

/* ==========================================================================
 * 一、公开接口
 * ========================================================================== */

/*
 * [主接口] 单腿虚拟力 -> 两关节力矩。
 *
 * 数学关系：
 *
 *     tau = J^T * [F, Tp]
 *
 *     tau[0] = J[0][0] * F + J[1][0] * Tp
 *     tau[1] = J[0][1] * F + J[1][1] * Tp
 *
 * 其中 J 由 FiveBar 提供：行依次为腿长方向、腿轴角方向，列依次为关节 1、
 * 关节 4。因此 J^T 的第 0 行对应关节 1，第 1 行对应关节 4。
 *
 * 参数：jacobian         -- [in]  2x2 Jacobian，不可为空；任一元素非有限值即失败
 *       force_N          -- [in]  腿长方向虚拟力 F
 *       pitch_torque_Nm  -- [in]  腿轴虚拟俯仰力矩 Tp
 *       joint_torque_Nm  -- [out] 两个关节力矩，不可为空
 * 返回：1 成功；0 入参为空或含非有限值。
 *
 * 失败语义：只要 joint_torque_Nm 非空，无论成功或失败都会先被清零，
 *           因此调用方失败时读到的必为 {0, 0}，不会残留上一次的力矩。
 */
uint8_t VMC_ConvertWrenchToJointTorque(
    const float jacobian[2][2],
    float force_N,
    float pitch_torque_Nm,
    float joint_torque_Nm[2]);

#endif
